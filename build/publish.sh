#!/usr/bin/env bash
# Publish the built site to the gh-pages branch.
#
# Only needed while CI can't do it: the agent's GitHub token lacks the
# `workflows` scope, so .github/workflows/deploy.yml couldn't be committed. Once
# a human adds that workflow (see docs/CI-WORKFLOWS.md), pushes to main deploy
# on their own and this script becomes redundant.
#
#   ./build/publish.sh

set -euo pipefail

cd "$(dirname "$0")/.."
REPO_ROOT=$(pwd)
SRC=$(git rev-parse --short HEAD)

if [[ -n "$(git status --porcelain)" ]]; then
  echo "warning: working tree is dirty — publishing the build of a tree that isn't committed" >&2
fi

echo "Building..."
node build/build.mjs

STAGE=$(mktemp -d)
trap 'rm -rf "$STAGE"' EXIT
# Pages serves this branch from /docs, not the branch root, and changing that
# setting needs Pages admin the token doesn't have — so publish into docs/.
mkdir -p "$STAGE/docs"
cp -r site/. "$STAGE/docs"/

cd "$STAGE"
git init -q
git checkout -q -b gh-pages
git add -A
git commit -q -m "Build site from main@${SRC}

Generated by build/build.mjs. Do not edit this branch by hand — it is
overwritten on every publish. Source lives on main."

REMOTE=$(git -C "$REPO_ROOT" remote get-url origin)
git remote add origin "$REMOTE"

# The branch only ever holds generated output, so replacing its history is the
# intent, not a mistake.
git push -f origin gh-pages

echo "Published $(cd "$REPO_ROOT" && git rev-parse --short HEAD) to gh-pages."
